import { Order } from '../types';
import { api } from './api';

declare global {
  interface Window {
    Razorpay: any;
  }
}

export interface RazorpayVerificationResult {
  success: boolean;
  order?: Order;
  error?: string;
  isSimulated?: boolean;
}

export const razorpayService = {
  /**
   * Check if standard Razorpay checkout script is loaded
   */
  isScriptLoaded(): boolean {
    return typeof window !== 'undefined' && typeof window.Razorpay === 'function';
  },

  /**
   * Launch Razorpay Checkout or fallback test runner
   */
  async processPayment(
    order: Order,
    onSuccess: (result: RazorpayVerificationResult) => void,
    onDismiss?: () => void
  ): Promise<void> {
    const keyId = import.meta.env.VITE_RAZORPAY_KEY_ID || 'rzp_test_college_demo';
    const isTestPlaceholder = keyId.includes('rzp_test_college_demo') || !this.isScriptLoaded();

    if (!isTestPlaceholder && this.isScriptLoaded()) {
      try {
        const options = {
          key: keyId,
          amount: Math.round(order.total_amount * 100), // In paise
          currency: 'INR',
          name: 'Smart Canteen System',
          description: `Order #${order.order_number}`,
          image: 'https://images.unsplash.com/photo-1546069901-ba9599a7e63c?auto=format&fit=crop&w=120&q=80',
          order_id: undefined, // Generated by backend edge function in live setup
          prefill: {
            name: order.profile?.full_name || 'Student',
            email: order.profile?.email || 'student@campus.edu',
            contact: order.profile?.phone || '9876543210',
          },
          theme: {
            color: '#16a34a', // Brand green
          },
          handler: async (response: {
            razorpay_payment_id: string;
            razorpay_order_id?: string;
            razorpay_signature?: string;
          }) => {
            try {
              // Server-side verification simulation / Edge function call
              const updatedOrder = await api.updatePaymentStatus(
                order.id,
                'paid',
                response.razorpay_payment_id
              );
              onSuccess({
                success: true,
                order: updatedOrder,
                isSimulated: false,
              });
            } catch (err: any) {
              onSuccess({
                success: false,
                error: err.message || 'Payment verification failed',
                isSimulated: false,
              });
            }
          },
          modal: {
            ondismiss: () => {
              if (onDismiss) onDismiss();
            },
          },
        };

        const rzp = new window.Razorpay(options);
        rzp.open();
        return;
      } catch (e) {
        console.warn('Real Razorpay initialization failed, opening test sandbox', e);
      }
    }

    // Interactive Test Mode Sandbox
    // Note clearly marked for development/college engineering evaluation
    return new Promise<void>((resolve) => {
      const modalId = 'rzp-test-sandbox-modal';
      let modalEl = document.getElementById(modalId);
      if (modalEl) modalEl.remove();

      modalEl = document.createElement('div');
      modalEl.id = modalId;
      modalEl.className = 'fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-fade-in';
      modalEl.innerHTML = `
        <div class="bg-white rounded-2xl shadow-2xl max-w-md w-full overflow-hidden border border-emerald-100 transform transition-all scale-100">
          <div class="bg-gradient-to-r from-emerald-600 to-green-700 px-6 py-4 text-white flex justify-between items-center">
            <div class="flex items-center space-x-2">
              <span class="inline-block w-2.5 h-2.5 rounded-full bg-emerald-300 animate-ping"></span>
              <h3 class="font-bold text-lg">Razorpay Test Gateway (Sandbox)</h3>
            </div>
            <span class="text-xs font-mono bg-white/20 px-2 py-0.5 rounded text-white">TEST MODE</span>
          </div>

          <div class="p-6 space-y-4">
            <div class="bg-amber-50 border border-amber-200 rounded-lg p-3 text-xs text-amber-900 leading-relaxed">
              <strong>Notice:</strong> This is a sandboxed gateway simulation demonstrating the college canteen payment workflow. No real currency is debited.
            </div>

            <div class="border rounded-xl p-4 bg-gray-50/70 space-y-2">
              <div class="flex justify-between text-sm">
                <span class="text-gray-500">Order ID:</span>
                <span class="font-mono font-medium">${order.order_number}</span>
              </div>
              <div class="flex justify-between text-sm">
                <span class="text-gray-500">Student:</span>
                <span class="font-medium">${order.profile?.full_name || 'Student'}</span>
              </div>
              <div class="flex justify-between text-base font-semibold border-t pt-2 mt-2">
                <span class="text-gray-800">Payable Amount:</span>
                <span class="text-emerald-700 font-bold text-lg">₹${order.total_amount.toFixed(2)}</span>
              </div>
            </div>

            <div class="space-y-2 pt-2">
              <button id="rzp-btn-success" class="w-full py-3 px-4 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl font-medium shadow-md hover:shadow-lg transition flex items-center justify-center space-x-2">
                <span>✓ Authorize & Simulate Success (UPI/Card)</span>
              </button>

              <button id="rzp-btn-fail" class="w-full py-2.5 px-4 bg-rose-50 hover:bg-rose-100 text-rose-700 border border-rose-200 rounded-xl font-medium transition text-sm">
                ✕ Simulate Payment Failure
              </button>

              <button id="rzp-btn-cancel" class="w-full py-2 text-gray-500 hover:text-gray-700 text-xs text-center transition">
                Cancel and return to checkout
              </button>
            </div>
          </div>
        </div>
      `;

      document.body.appendChild(modalEl);

      const cleanup = () => {
        if (modalEl && modalEl.parentNode) modalEl.parentNode.removeChild(modalEl);
      };

      document.getElementById('rzp-btn-success')?.addEventListener('click', async () => {
        cleanup();
        const fakePaymentId = 'pay_' + Math.random().toString(36).substring(2, 14);
        const updated = await api.updatePaymentStatus(order.id, 'paid', fakePaymentId);
        onSuccess({
          success: true,
          order: updated,
          isSimulated: true,
        });
        resolve();
      });

      document.getElementById('rzp-btn-fail')?.addEventListener('click', async () => {
        cleanup();
        const updated = await api.updatePaymentStatus(order.id, 'failed');
        onSuccess({
          success: false,
          error: 'Payment was declined by issuing bank (Simulated failure)',
          order: updated,
          isSimulated: true,
        });
        resolve();
      });

      document.getElementById('rzp-btn-cancel')?.addEventListener('click', () => {
        cleanup();
        if (onDismiss) onDismiss();
        resolve();
      });
    });
  },
};
